import * as fs from 'node:fs'
import * as path from 'node:path'

import { dbDir, repoRoot, requireDatabaseUrl, run, schemaNames } from './lib.ts'

let url = requireDatabaseUrl()
let outDir = path.join(dbDir, 'dump')
fs.mkdirSync(outDir, { recursive: true })
let outFile = path.join(outDir, 'schema.sql')

let args = [
  '--schema-only',
  '--no-owner',
  '--no-privileges',
  '--quote-all-identifiers',
  ...schemaNames().flatMap((schema) => ['--schema', schema]),
  '--file',
  outFile,
  url,
]

run(process.env.PG_DUMP ?? 'pg_dump', args, { cwd: repoRoot })
let header = `-- Generated by npm run db:dump. Do not edit.\n-- Source database: ${url.replace(/:[^:@/]+@/, ':***@')}\n\n`
fs.writeFileSync(outFile, header + fs.readFileSync(outFile, 'utf8'))
console.log(`wrote ${path.relative(repoRoot, outFile)}`)
